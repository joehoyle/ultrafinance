-- Public IDs stay stable. Large derived tables and outlet/provider ownership
-- use compact internal keys; user-authored inputs and audit references retain
-- their public IDs.
LOCK TABLE merchants,aliases,merchant_search,merchant_identity_keys,location_records,foursquare_unlocated IN ACCESS EXCLUSIVE MODE;
ALTER TABLE merchants ADD COLUMN merchant_key BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE merchants ADD CONSTRAINT merchants_key_unique UNIQUE(merchant_key);
CREATE FUNCTION merchant_key(text) RETURNS bigint LANGUAGE sql STABLE STRICT AS
 'SELECT merchant_key FROM merchants WHERE id=$1';
CREATE FUNCTION merchant_public_id(bigint) RETURNS text LANGUAGE sql STABLE STRICT AS
 'SELECT id FROM merchants WHERE merchant_key=$1';
CREATE FUNCTION merchant_keys(text[]) RETURNS bigint[] LANGUAGE sql STABLE STRICT AS
 'SELECT coalesce(array_agg(merchant_key),ARRAY[]::bigint[]) FROM merchants WHERE id=ANY($1)';
CREATE TEMP TABLE identity_view_grants ON COMMIT DROP AS
SELECT grantee,privilege_type,is_grantable FROM information_schema.table_privileges
WHERE table_schema=current_schema() AND table_name='source_identities';
DROP VIEW source_identities;
CREATE TEMP TABLE numeric_location_trigger_mode ON COMMIT DROP AS
SELECT tgenabled FROM pg_trigger WHERE tgrelid='location_records'::regclass AND tgname='location_merchant';
DROP TRIGGER location_merchant ON location_records;
DO $$ DECLARE t text; fk record; BEGIN
 FOR t IN SELECT unnest(ARRAY['aliases','merchant_search','merchant_identity_keys','location_records','foursquare_unlocated']) LOOP
  FOR fk IN SELECT conname FROM pg_constraint WHERE conrelid=t::regclass AND contype='f' AND confrelid='merchants'::regclass LOOP
   EXECUTE format('ALTER TABLE %I DROP CONSTRAINT %I',t,fk.conname);
  END LOOP;
  -- A set-based join backfills once, avoiding a random lookup per stored link.
  EXECUTE format('ALTER TABLE %I ADD COLUMN numeric_owner bigint',t);
  EXECUTE format('UPDATE %I r SET numeric_owner=m.merchant_key FROM merchants m WHERE m.id=r.merchant_id',t);
  EXECUTE format('ALTER TABLE %I ALTER COLUMN merchant_id TYPE bigint USING numeric_owner, DROP COLUMN numeric_owner',t);
  EXECUTE format('ALTER TABLE %I ADD CONSTRAINT %I FOREIGN KEY(merchant_id) REFERENCES merchants(merchant_key)%s',t,t||'_merchant_id_fkey',
   CASE WHEN t IN ('aliases','merchant_search','merchant_identity_keys') THEN ' ON DELETE CASCADE' ELSE '' END);
 END LOOP;
END $$;
CREATE OR REPLACE FUNCTION resolve_location_merchant() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.merchant_source IS NOT NULL THEN
  SELECT m.merchant_key INTO NEW.merchant_id FROM source_records s JOIN merchants m ON m.id=s.merchant_id
  WHERE s.source=NEW.merchant_source AND s.external_id=NEW.merchant_external_id;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER location_merchant BEFORE INSERT OR UPDATE OF merchant_id,merchant_source,merchant_external_id
ON location_records FOR EACH ROW EXECUTE FUNCTION resolve_location_merchant();
DO $$ DECLARE mode "char"; BEGIN
 SELECT tgenabled INTO mode FROM numeric_location_trigger_mode;
 IF mode='D' THEN ALTER TABLE location_records DISABLE TRIGGER location_merchant;
 ELSIF mode='A' THEN ALTER TABLE location_records ENABLE ALWAYS TRIGGER location_merchant;
 ELSIF mode='R' THEN ALTER TABLE location_records ENABLE REPLICA TRIGGER location_merchant;
 END IF;
END $$;
CREATE OR REPLACE FUNCTION relink_source_locations() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 UPDATE location_records SET merchant_id=merchant_key(NEW.merchant_id)
 WHERE merchant_source=NEW.source AND merchant_external_id=NEW.external_id
 AND merchant_id IS DISTINCT FROM merchant_key(NEW.merchant_id);
 RETURN NEW;
END $$;
CREATE VIEW source_identities AS
 SELECT source,external_id,merchant_id FROM source_records
 UNION ALL SELECT l.source,l.external_id,m.id FROM location_records l JOIN merchants m ON m.merchant_key=l.merchant_id WHERE l.source='foursquare'
 UNION ALL SELECT 'foursquare',u.external_id,m.id FROM foursquare_unlocated u JOIN merchants m ON m.merchant_key=u.merchant_id;
DO $$ DECLARE g record; who text; BEGIN
 FOR g IN SELECT * FROM identity_view_grants LOOP
  who := CASE WHEN g.grantee='PUBLIC' THEN 'PUBLIC' ELSE quote_ident(g.grantee) END;
  EXECUTE 'GRANT SELECT ON source_identities TO '||who||CASE WHEN g.is_grantable='YES' THEN ' WITH GRANT OPTION' ELSE '' END;
 END LOOP;
 -- Existing runtime writers need the new identity sequence.
 FOR g IN SELECT grantee FROM information_schema.table_privileges
 WHERE table_schema=current_schema() AND table_name='merchants' AND privilege_type='INSERT' LOOP
  who := CASE WHEN g.grantee='PUBLIC' THEN 'PUBLIC' ELSE quote_ident(g.grantee) END;
  EXECUTE 'GRANT USAGE ON SEQUENCE merchants_merchant_key_seq TO '||who;
 END LOOP;
END $$;
