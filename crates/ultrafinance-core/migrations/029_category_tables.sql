-- Shared taxonomy and normalized, integer category references.
SET LOCAL statement_timeout='0';
SET LOCAL idle_in_transaction_session_timeout='0';
CREATE TABLE categories (
 id INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 external_id TEXT NOT NULL UNIQUE,
 name TEXT,
 parent_id INTEGER REFERENCES categories(id),
 CHECK(parent_id IS NULL OR parent_id<>id)
);
CREATE INDEX categories_parent ON categories(parent_id);
CREATE TABLE merchant_categories (
 merchant_id BIGINT NOT NULL REFERENCES merchants(merchant_key) ON DELETE CASCADE,
 category_id INTEGER NOT NULL REFERENCES categories(id),
 PRIMARY KEY(merchant_id,category_id)
);
CREATE TABLE manual_merchant_categories (
 merchant_id TEXT NOT NULL REFERENCES manual_merchants(id) ON DELETE CASCADE,
 category_id INTEGER NOT NULL REFERENCES categories(id),
 PRIMARY KEY(merchant_id,category_id)
);
CREATE TABLE source_record_categories (
 source TEXT NOT NULL,
 external_id TEXT NOT NULL,
 category_id INTEGER NOT NULL REFERENCES categories(id),
 FOREIGN KEY(source,external_id) REFERENCES source_records(source,external_id) ON DELETE CASCADE ON UPDATE CASCADE,
 PRIMARY KEY(source,external_id,category_id)
);
CREATE TABLE foursquare_place_categories (
 external_id TEXT NOT NULL REFERENCES foursquare_categories(external_id) ON DELETE CASCADE ON UPDATE CASCADE,
 category_id INTEGER NOT NULL REFERENCES categories(id),
 PRIMARY KEY(external_id,category_id)
);
