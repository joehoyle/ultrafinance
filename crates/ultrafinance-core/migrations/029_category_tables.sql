 SELECT ARRAY(SELECT c.external_id FROM categories c JOIN (
 SELECT category_id FROM merchant_categories WHERE NOT manual AND merchant_id=merchant_key(owner)
 UNION ALL SELECT category_id FROM manual_merchant_categories WHERE manual AND merchant_id=owner
 ) a ON a.category_id=c.id ORDER BY c.external_id)
$$;
CREATE FUNCTION source_category_ids(provider TEXT, place TEXT) RETURNS TEXT[] LANGUAGE SQL STABLE AS $$
 SELECT ARRAY(SELECT c.external_id FROM source_record_categories a JOIN categories c ON c.id=a.category_id WHERE a.source=provider AND a.external_id=place ORDER BY c.external_id)
$$;
CREATE FUNCTION foursquare_category_ids(place TEXT) RETURNS TEXT[] LANGUAGE SQL STABLE AS $$
 SELECT ARRAY(SELECT c.external_id FROM foursquare_place_categories a JOIN categories c ON c.id=a.category_id WHERE a.external_id=place ORDER BY c.external_id)
$$;
CREATE FUNCTION category_details(ids TEXT[]) RETURNS JSONB LANGUAGE SQL STABLE AS $$
 SELECT COALESCE(jsonb_agg(jsonb_strip_nulls(jsonb_build_object('id',leaf.external_id,'name',leaf.name,'path',CASE WHEN leaf.name IS NULL THEN '[]'::jsonb ELSE (
 WITH RECURSIVE ancestors AS (
 SELECT id,external_id,name,parent_id,ARRAY[id] AS visited,0 AS depth FROM categories WHERE id=leaf.id
 UNION ALL SELECT c.id,c.external_id,c.name,c.parent_id,a.visited||c.id,a.depth+1 FROM categories c JOIN ancestors a ON c.id=a.parent_id WHERE NOT c.id=ANY(a.visited)
 ) SELECT jsonb_agg(jsonb_build_object('id',external_id,'name',name) ORDER BY depth DESC) FROM ancestors
 ) END)) ORDER BY leaf.external_id),'[]'::jsonb) FROM categories leaf WHERE leaf.external_id=ANY(ids)
$$;
-- Transition tables invalidate once per changed batch, including bulk COPY.
CREATE FUNCTION advance_category_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF EXISTS(SELECT 1 FROM changed_categories) THEN
  UPDATE catalog_revision SET revision=revision+1;
 END IF;
 RETURN NULL;
END $$;
CREATE TRIGGER categories_revision_insert AFTER INSERT ON categories REFERENCING NEW TABLE AS changed_categories FOR EACH STATEMENT EXECUTE FUNCTION advance_category_revision();
CREATE TRIGGER categories_revision_update AFTER UPDATE ON categories REFERENCING NEW TABLE AS changed_categories FOR EACH STATEMENT EXECUTE FUNCTION advance_category_revision();
CREATE TRIGGER categories_revision_delete AFTER DELETE ON categories REFERENCING OLD TABLE AS changed_categories FOR EACH STATEMENT EXECUTE FUNCTION advance_category_revision();
CREATE TRIGGER merchant_categories_revision_insert AFTER INSERT ON merchant_categories REFERENCING NEW TABLE AS changed_categories FOR EACH STATEMENT EXECUTE FUNCTION advance_category_revision();
CREATE TRIGGER merchant_categories_revision_update AFTER UPDATE ON merchant_categories REFERENCING NEW TABLE AS changed_categories FOR EACH STATEMENT EXECUTE FUNCTION advance_category_revision();
CREATE TRIGGER merchant_categories_revision_delete AFTER DELETE ON merchant_categories REFERENCING OLD TABLE AS changed_categories FOR EACH STATEMENT EXECUTE FUNCTION advance_category_revision();
CREATE TRIGGER categories_revision_truncate AFTER TRUNCATE ON categories FOR EACH STATEMENT EXECUTE FUNCTION advance_catalog_revision();
CREATE TRIGGER merchant_categories_revision_truncate AFTER TRUNCATE ON merchant_categories FOR EACH STATEMENT EXECUTE FUNCTION advance_catalog_revision();
